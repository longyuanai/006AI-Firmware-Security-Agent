"""Regenerate this corpus entry's rootfs/ and expected.yml from the manifest.

The manifest is the unmodified official OpenWrt build manifest checked into
samples/ (see samples/README.md for its source URL and SHA-256) — genuine
external data this benchmark did not author. This script only reshapes it
into the opkg status-file format detectors/packages.py actually parses, and
into the normalized version form Component.version carries after detection.

Run from the repository root:

    poetry run python benchmarks/corpus/openwrt-23.05.5-ath79-tiny/generate.py

The output is checked in rather than generated at benchmark-run time, so the
corpus stays a stable, reviewable artifact independent of how the manifest
parsing code evolves.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from ai_firmware_agent.detectors.packages import upstream_version

HERE = Path(__file__).parent
MANIFEST = HERE.parents[2] / "samples" / "openwrt-23.05.5-ath79-tiny.manifest"
STATUS_PATH = HERE / "rootfs" / "usr" / "lib" / "opkg" / "status"
EXPECTED_PATH = HERE / "expected.yml"


def _entries() -> list[tuple[str, str]]:
    entries: list[tuple[str, str]] = []
    for raw_line in MANIFEST.read_text(encoding="utf-8").splitlines():
        name, separator, version = raw_line.partition(" - ")
        if not separator:
            continue
        entries.append((name.strip(), version.strip()))
    return entries


def main() -> None:
    entries = _entries()

    stanzas = "\n".join(
        f"Package: {name}\nVersion: {version}\nStatus: install user installed\n"
        for name, version in entries
    )
    STATUS_PATH.write_text(stanzas, encoding="utf-8")

    expected = {
        "components": [
            {"name": name.lower(), "version": upstream_version(version)}
            for name, version in entries
        ]
    }
    header = (
        "# Generated by generate.py from samples/openwrt-23.05.5-ath79-tiny.manifest.\n"
        "# Do not hand-edit; re-run generate.py after any manifest change.\n"
    )
    EXPECTED_PATH.write_text(
        header + yaml.safe_dump(expected, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    print(f"wrote {len(entries)} packages to {STATUS_PATH}")
    print(f"wrote expected.yml with {len(expected['components'])} components")


if __name__ == "__main__":
    main()
